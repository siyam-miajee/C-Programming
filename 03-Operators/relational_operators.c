#include<stdio.h>
int main()
{
    int a = 10;
    int b = 5;
    //Output- 1 = True, 0 = False
    printf("a > b  : %d\n", a > b);
    printf("a < b  : %d\n", a < b);
    printf("a >= b : %d\n", a >= b);
    printf("a <= b : %d\n", a <= b);
    printf("a == b : %d\n", a == b);
    printf("a != b : %d\n", a != b);
    return 0;
}
